//! Self-installation helpers shared by the rtunnel binaries.
//!
//! These helpers keep packaging details inside the shipped executables so that
//! a downloaded binary can install itself without a source checkout.

use std::ffi::OsStr;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Default directory for system-wide executables.
pub const DEFAULT_BIN_DIR: &str = "/usr/local/bin";

/// File name suffix used for executables on the current platform.
pub const EXE_SUFFIX: &str = if cfg!(windows) { ".exe" } else { "" };

/// Default directory for systemd unit files.
pub const DEFAULT_SYSTEMD_DIR: &str = "/etc/systemd/system";

/// Parent directory that systemd manages through `StateDirectory=`.
pub const SYSTEMD_STATE_ROOT: &str = "/var/lib";

/// OpenSSH directive that loads snippets generated by `rtunnel ssh-config`.
const SSH_INCLUDE_LINE: &str = "Include ~/.ssh/rtunnel.d/*";

/// Returns `true` if the current process has effective UID 0.
#[must_use]
pub fn is_root() -> bool {
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt;

        fs::metadata("/proc/self").is_ok_and(|metadata| metadata.uid() == 0)
    }
    #[cfg(not(unix))]
    {
        false
    }
}

/// Returns an error unless the process runs as root or administrator.
///
/// # Errors
///
/// Returns [`io::ErrorKind::PermissionDenied`] when the effective user is not root.
pub fn ensure_root() -> io::Result<()> {
    if is_root() {
        Ok(())
    } else {
        Err(io::Error::new(
            io::ErrorKind::PermissionDenied,
            "this command must run as root or administrator (try sudo)",
        ))
    }
}

/// Returns the platform-specific executable file name for `stem`.
///
/// On Windows this appends `.exe`; on other platforms the name is unchanged.
#[must_use]
pub fn executable_name(stem: &str) -> String {
    let mut name = String::with_capacity(stem.len() + EXE_SUFFIX.len());
    name.push_str(stem);
    name.push_str(EXE_SUFFIX);
    name
}

/// Returns `true` when `dir` appears in the supplied `PATH`-style value.
///
/// Entries are compared case-insensitively on Windows, quotes are ignored, and
/// trailing path separators do not affect the result.
#[must_use]
pub fn path_contains(path_value: &OsStr, dir: &Path) -> bool {
    let target = normalize_path_entry(dir.as_os_str());
    !target.is_empty()
        && std::env::split_paths(path_value)
            .any(|entry| normalize_path_entry(entry.as_os_str()) == target)
}

/// Returns `true` when `dir` appears in the current process `PATH`.
#[must_use]
pub fn is_dir_on_path(dir: &Path) -> bool {
    std::env::var_os("PATH").is_some_and(|value| path_contains(&value, dir))
}

/// Adds `dir` to the current user's persistent `PATH` on Windows.
///
/// Returns `true` when the entry was added, or `false` when it was already
/// present. This is a no-op returning `false` on non-Windows platforms, where
/// `PATH` is managed by the shell.
///
/// # Errors
///
/// Returns an error when the user environment registry key cannot be read or
/// written, or when `dir` contains a semicolon.
#[cfg(windows)]
pub fn add_to_user_path(dir: &Path) -> io::Result<bool> {
    use winreg::RegKey;
    use winreg::RegValue;
    use winreg::enums::{HKEY_CURRENT_USER, RegType};

    let dir_text = dir.to_string_lossy();
    if dir_text.contains(';') {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "PATH entries must not contain semicolons",
        ));
    }

    let (environment, _) = RegKey::predef(HKEY_CURRENT_USER).create_subkey("Environment")?;
    let raw = match environment.get_raw_value("Path") {
        Ok(value) => Some(value),
        Err(error) if error.kind() == io::ErrorKind::NotFound => None,
        Err(error) => return Err(error),
    };

    let current = raw
        .as_ref()
        .map_or_else(String::new, |value| decode_reg_string(&value.bytes));
    if path_contains(OsStr::new(&current), dir) {
        return Ok(false);
    }

    let updated = if current.trim().is_empty() {
        dir_text.into_owned()
    } else {
        format!("{};{dir_text}", current.trim_end_matches(';'))
    };
    let vtype = raw
        .as_ref()
        .map_or(RegType::REG_EXPAND_SZ, |value| value.vtype.clone());
    environment.set_raw_value(
        "Path",
        &RegValue {
            vtype,
            bytes: encode_reg_string(&updated).into(),
        },
    )?;
    Ok(true)
}

/// Adds `dir` to the current user's persistent `PATH`.
///
/// This is a no-op on non-Windows platforms; see the Windows implementation.
///
/// # Errors
///
/// Never returns an error on non-Windows platforms.
#[cfg(not(windows))]
#[allow(clippy::unnecessary_wraps)]
pub fn add_to_user_path(_dir: &Path) -> io::Result<bool> {
    Ok(false)
}

fn normalize_path_entry(entry: &OsStr) -> String {
    let text = entry.to_string_lossy();
    let text = text.trim().trim_matches('"');
    let trimmed = text.trim_end_matches(['/', '\\']);
    let text = if trimmed.is_empty() { text } else { trimmed };
    if cfg!(windows) {
        text.to_ascii_lowercase()
    } else {
        text.to_string()
    }
}

#[cfg(windows)]
fn decode_reg_string(bytes: &[u8]) -> String {
    let (chunks, _) = bytes.as_chunks::<2>();
    let units: Vec<u16> = chunks
        .iter()
        .map(|chunk| u16::from_le_bytes(*chunk))
        .collect();
    let end = units
        .iter()
        .position(|&unit| unit == 0)
        .unwrap_or(units.len());
    String::from_utf16_lossy(&units[..end])
}

#[cfg(windows)]
fn encode_reg_string(text: &str) -> Vec<u8> {
    let mut bytes: Vec<u8> = text.encode_utf16().flat_map(u16::to_le_bytes).collect();
    bytes.extend_from_slice(&[0, 0]);
    bytes
}

/// Creates `path` and applies mode `0700` on Unix.
///
/// # Errors
///
/// Returns an error when the directory cannot be created or its permissions
/// cannot be changed.
pub fn create_private_dir(path: &Path) -> io::Result<()> {
    fs::create_dir_all(path)?;
    set_mode(path, 0o700)
}

/// Copies the currently running executable to `dest`, replacing `dest`
/// atomically where the platform allows it.
///
/// The source and destination may refer to the same file, in which case no
/// copy is performed. The caller must have permission to write to the
/// destination directory.
///
/// # Errors
///
/// Returns an error when the current executable cannot be resolved, the
/// destination directory cannot be created, or the copy, chmod, or rename
/// operation fails.
pub fn install_self(dest: &Path) -> io::Result<PathBuf> {
    let source = std::env::current_exe()?;
    let dest = absolute_path(dest)?;

    if same_file(&source, &dest) {
        return Ok(dest);
    }

    let parent = dest.parent().ok_or_else(|| {
        io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("destination has no parent directory: {}", dest.display()),
        )
    })?;
    fs::create_dir_all(parent)?;

    let temporary = temporary_path(&dest)?;
    let installed = fs::copy(&source, &temporary)
        .and_then(|_| set_mode(&temporary, 0o755))
        .and_then(|()| replace_file(&temporary, &dest));
    if installed.is_err() {
        let _ = fs::remove_file(&temporary);
    }
    installed?;

    Ok(dest)
}

/// Environment applied to the generated host service.
///
/// The host daemon logs to the service manager's journal, so the agent is kept
/// quiet during normal unattended operation while errors remain visible.
#[cfg(target_os = "linux")]
const SERVICE_ENVIRONMENT: &str = "RUST_LOG=rtunnel_agent=warn";

/// Renders the Linux `systemd` unit for the host daemon.
#[cfg(target_os = "linux")]
fn render_host_unit(exec_cmd: &str) -> String {
    let template = r"[Unit]
Description=rtunnel background host daemon
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
Environment=__SERVICE_ENVIRONMENT__
ExecStart=__EXEC_CMD__
Restart=always
RestartSec=5
UMask=0077

[Install]
WantedBy=multi-user.target
";
    template
        .replace("__SERVICE_ENVIRONMENT__", SERVICE_ENVIRONMENT)
        .replace("__EXEC_CMD__", exec_cmd)
}

/// Installs and enables the background service across Linux (`systemd`), macOS (`launchd`), and Windows (`sc.exe`).
///
/// # Errors
///
/// Returns an error if generating, writing, or registering the service fails with the platform supervisor.
pub fn install_service(
    service_name: &str,
    bin_path: &Path,
    args: &[&str],
    _state_dir: &Path,
) -> io::Result<()> {
    #[cfg(target_os = "linux")]
    {
        let exec_cmd = format!("{} {}", bin_path.display(), args.join(" "));
        let contents = render_host_unit(&exec_cmd);
        let unit_filename = format!("{service_name}.service");
        install_unit(&unit_filename, &contents)?;
        enable_service(&unit_filename, true)?;
        Ok(())
    }

    #[cfg(target_os = "macos")]
    {
        let plist_path = PathBuf::from(format!(
            "/Library/LaunchDaemons/com.rtunnel.{service_name}.plist"
        ));
        let mut program_args = vec![bin_path.to_string_lossy().into_owned()];
        program_args.extend(args.iter().map(|&a| a.to_string()));
        let args_xml = program_args
            .iter()
            .map(|arg| format!("        <string>{arg}</string>"))
            .collect::<Vec<_>>()
            .join("\n");

        let plist_content = format!(
            r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>com.rtunnel.{service_name}</string>
    <key>ProgramArguments</key>
    <array>
{args_xml}
    </array>
    <key>RunAtLoad</key>
    <true/>
    <key>KeepAlive</key>
    <true/>
    <key>EnvironmentVariables</key>
    <dict>
        <key>RUST_LOG</key>
        <string>rtunnel_agent=warn</string>
    </dict>
    <key>StandardErrorPath</key>
    <string>{}/daemon.log</string>
</dict>
</plist>
"#,
            _state_dir.display()
        );

        fs::write(&plist_path, plist_content)?;
        set_mode(&plist_path, 0o644)?;
        let output = Command::new("launchctl")
            .args(["load", "-w", &plist_path.to_string_lossy()])
            .output()?;
        if !output.status.success() {
            return Err(io::Error::other(format!(
                "launchctl load failed: {}",
                String::from_utf8_lossy(&output.stderr).trim()
            )));
        }
        Ok(())
    }

    #[cfg(windows)]
    {
        let bin_args = format!("{} {}", bin_path.display(), args.join(" "));
        let status = Command::new("sc.exe")
            .args([
                "create",
                service_name,
                &format!("binPath= {bin_args}"),
                "start= auto",
            ])
            .status()?;
        if !status.success() {
            return Err(io::Error::other("sc.exe create service failed"));
        }
        let start_status = Command::new("sc.exe")
            .args(["start", service_name])
            .status()?;
        if !start_status.success() {
            return Err(io::Error::other("sc.exe start service failed"));
        }
        Ok(())
    }

    #[cfg(not(any(target_os = "linux", target_os = "macos", windows)))]
    {
        let _ = (service_name, bin_path, args, _state_dir);
        Err(io::Error::new(
            io::ErrorKind::Unsupported,
            "platform service manager not supported",
        ))
    }
}

/// Starts an installed background service for `service_name`.
///
/// # Errors
///
/// Returns an error when the platform service manager is unavailable or rejects
/// the start request.
