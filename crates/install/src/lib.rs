#![forbid(unsafe_code)]
#![deny(clippy::all, clippy::pedantic)]

//! Self-installation helpers shared by the rtunnel binaries.
//!
//! These helpers keep packaging details inside the shipped executables so that
//! a downloaded binary can install itself without a source checkout.

use std::ffi::OsStr;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Default directory for system-wide executables.
pub const DEFAULT_BIN_DIR: &str = "/usr/local/bin";

/// File name suffix used for executables on the current platform.
pub const EXE_SUFFIX: &str = if cfg!(windows) { ".exe" } else { "" };

/// Default directory for systemd unit files.
pub const DEFAULT_SYSTEMD_DIR: &str = "/etc/systemd/system";

/// Parent directory that systemd manages through `StateDirectory=`.
pub const SYSTEMD_STATE_ROOT: &str = "/var/lib";

/// OpenSSH directive that loads snippets generated by `rtunnel ssh-config`.
const SSH_INCLUDE_LINE: &str = "Include ~/.ssh/rtunnel.d/*";

/// Returns `true` if the current process has effective UID 0.
#[must_use]
pub fn is_root() -> bool {
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt;

        fs::metadata("/proc/self").is_ok_and(|metadata| metadata.uid() == 0)
    }
    #[cfg(not(unix))]
    {
        false
    }
}

/// Returns an error unless the process runs as root.
///
/// # Errors
///
/// Returns [`io::ErrorKind::PermissionDenied`] when the effective user is not
/// root.
pub fn ensure_root() -> io::Result<()> {
    if is_root() {
        Ok(())
    } else {
        Err(io::Error::new(
            io::ErrorKind::PermissionDenied,
            "this command must run as root (try sudo)",
        ))
    }
}

/// Returns the platform-specific executable file name for `stem`.
///
/// On Windows this appends `.exe`; on other platforms the name is unchanged.
#[must_use]
pub fn executable_name(stem: &str) -> String {
    let mut name = String::with_capacity(stem.len() + EXE_SUFFIX.len());
    name.push_str(stem);
    name.push_str(EXE_SUFFIX);
    name
}

/// Returns `true` when `dir` appears in the supplied `PATH`-style value.
///
/// Entries are compared case-insensitively on Windows, quotes are ignored, and
/// trailing path separators do not affect the result.
#[must_use]
pub fn path_contains(path_value: &OsStr, dir: &Path) -> bool {
    let target = normalize_path_entry(dir.as_os_str());
    !target.is_empty()
        && std::env::split_paths(path_value)
            .any(|entry| normalize_path_entry(entry.as_os_str()) == target)
}

/// Returns `true` when `dir` appears in the current process `PATH`.
#[must_use]
pub fn is_dir_on_path(dir: &Path) -> bool {
    std::env::var_os("PATH").is_some_and(|value| path_contains(&value, dir))
}

/// Adds `dir` to the current user's persistent `PATH` on Windows.
///
/// Returns `true` when the entry was added, or `false` when it was already
/// present. This is a no-op returning `false` on non-Windows platforms, where
/// `PATH` is managed by the shell.
///
/// # Errors
///
/// Returns an error when the user environment registry key cannot be read or
/// written, or when `dir` contains a semicolon.
#[cfg(windows)]
pub fn add_to_user_path(dir: &Path) -> io::Result<bool> {
    use winreg::RegKey;
    use winreg::RegValue;
    use winreg::enums::{HKEY_CURRENT_USER, RegType};

    let dir_text = dir.to_string_lossy();
    if dir_text.contains(';') {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "PATH entries must not contain semicolons",
        ));
    }

    let (environment, _) = RegKey::predef(HKEY_CURRENT_USER).create_subkey("Environment")?;
    let raw = match environment.get_raw_value("Path") {
        Ok(value) => Some(value),
        Err(error) if error.kind() == io::ErrorKind::NotFound => None,
        Err(error) => return Err(error),
    };

    let current = raw
        .as_ref()
        .map_or_else(String::new, |value| decode_reg_string(&value.bytes));
    if path_contains(OsStr::new(&current), dir) {
        return Ok(false);
    }

    let updated = if current.trim().is_empty() {
        dir_text.into_owned()
    } else {
        format!("{};{dir_text}", current.trim_end_matches(';'))
    };
    let vtype = raw
        .as_ref()
        .map_or(RegType::REG_EXPAND_SZ, |value| value.vtype.clone());
    environment.set_raw_value(
        "Path",
        &RegValue {
            vtype,
            bytes: encode_reg_string(&updated).into(),
        },
    )?;
    Ok(true)
}

/// Adds `dir` to the current user's persistent `PATH`.
///
/// This is a no-op on non-Windows platforms; see the Windows implementation.
///
/// # Errors
///
/// Never returns an error on non-Windows platforms.
#[cfg(not(windows))]
pub fn add_to_user_path(_dir: &Path) -> io::Result<bool> {
    Ok(false)
}

fn normalize_path_entry(entry: &OsStr) -> String {
    let text = entry.to_string_lossy();
    let text = text.trim().trim_matches('"');
    let trimmed = text.trim_end_matches(['/', '\\']);
    // Preserve a bare root such as `/` or `\` instead of normalizing it to an
    // empty string, which would match empty `PATH` entries.
    let text = if trimmed.is_empty() { text } else { trimmed };
    if cfg!(windows) {
        text.to_ascii_lowercase()
    } else {
        text.to_string()
    }
}

#[cfg(windows)]
fn decode_reg_string(bytes: &[u8]) -> String {
    let (chunks, _) = bytes.as_chunks::<2>();
    let units: Vec<u16> = chunks
        .iter()
        .map(|chunk| u16::from_le_bytes(*chunk))
        .collect();
    let end = units
        .iter()
        .position(|&unit| unit == 0)
        .unwrap_or(units.len());
    String::from_utf16_lossy(&units[..end])
}

#[cfg(windows)]
fn encode_reg_string(text: &str) -> Vec<u8> {
    let mut bytes: Vec<u8> = text.encode_utf16().flat_map(u16::to_le_bytes).collect();
    bytes.extend_from_slice(&[0, 0]);
    bytes
}

/// Creates `path` and applies mode `0700` on Unix.
///
/// # Errors
///
/// Returns an error when the directory cannot be created or its permissions
/// cannot be changed.
pub fn create_private_dir(path: &Path) -> io::Result<()> {
    fs::create_dir_all(path)?;
    set_mode(path, 0o700)
}

/// Copies the currently running executable to `dest`, replacing `dest`
/// atomically where the platform allows it.
///
/// The source and destination may refer to the same file, in which case no
/// copy is performed. The caller must have permission to write to the
/// destination directory.
///
/// # Errors
///
/// Returns an error when the current executable cannot be resolved, the
/// destination directory cannot be created, or the copy, chmod, or rename
/// operation fails.
pub fn install_self(dest: &Path) -> io::Result<PathBuf> {
    let source = std::env::current_exe()?;
    let dest = absolute_path(dest)?;

    if same_file(&source, &dest) {
        return Ok(dest);
    }

    let parent = dest.parent().ok_or_else(|| {
        io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("destination has no parent directory: {}", dest.display()),
        )
    })?;
    fs::create_dir_all(parent)?;

    let temporary = temporary_path(&dest)?;
    let installed = fs::copy(&source, &temporary)
        .and_then(|_| set_mode(&temporary, 0o755))
        .and_then(|()| replace_file(&temporary, &dest));
    if installed.is_err() {
        let _ = fs::remove_file(&temporary);
    }
    installed?;

    Ok(dest)
}

/// Writes a systemd unit to [`DEFAULT_SYSTEMD_DIR`].
///
/// # Errors
///
/// Returns an error when the unit directory cannot be created or the unit file
/// cannot be written, chmodded, or renamed into place.
pub fn install_unit(unit_name: &str, contents: &str) -> io::Result<PathBuf> {
    if unit_name.is_empty() || unit_name.contains('/') {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("invalid systemd unit name: {unit_name}"),
        ));
    }

    let path = Path::new(DEFAULT_SYSTEMD_DIR).join(unit_name);
    let temporary = temporary_path(&path)?;
    let installed = fs::write(&temporary, contents)
        .and_then(|()| set_mode(&temporary, 0o644))
        .and_then(|()| replace_file(&temporary, &path));
    if installed.is_err() {
        let _ = fs::remove_file(&temporary);
    }
    installed?;

    Ok(path)
}

/// Renders a unit template using the executable command and state directory.
///
/// `ExecStart=` is replaced with `exec_start`. When `state_dir` is a direct
/// child of [`SYSTEMD_STATE_ROOT`], `StateDirectory=` is pointed at it so
/// systemd creates and owns the directory. Otherwise the `StateDirectory=`
/// directive is removed and `ReadWritePaths=` is added, which keeps the unit
/// working with `ProtectSystem=strict` for custom locations.
#[must_use]
pub fn render_unit(template: &str, exec_start: &str, state_dir: &Path) -> String {
    let managed_name = systemd_state_name(state_dir);
    let mut rendered = String::with_capacity(template.len() + 128);
    let mut replaced_exec_start = false;

    for line in template.lines() {
        if line.starts_with("ExecStart=") {
            rendered.push_str("ExecStart=");
            rendered.push_str(exec_start);
            rendered.push('\n');
            replaced_exec_start = true;
            if managed_name.is_none() {
                rendered.push_str("ReadWritePaths=");
                rendered.push_str(&state_dir.to_string_lossy());
                rendered.push('\n');
            }
        } else if line.starts_with("StateDirectory=") {
            if let Some(name) = managed_name {
                rendered.push_str("StateDirectory=");
                rendered.push_str(name);
                rendered.push('\n');
            }
        } else {
            rendered.push_str(line);
            rendered.push('\n');
        }
    }

    // The embedded templates always contain ExecStart, but keep the renderer
    // useful for callers that pass a minimal template.
    if !replaced_exec_start {
        rendered.push_str("ExecStart=");
        rendered.push_str(exec_start);
        rendered.push('\n');
    }

    rendered
}

/// Validates a path that will be embedded in a systemd unit file.
///
/// # Errors
///
/// Returns an error when the path is not absolute, is not valid UTF-8, is
/// empty, or contains whitespace. Systemd splits several unit directives on
/// whitespace, so rejecting such paths keeps the rendered unit unambiguous.
pub fn validate_unit_path(path: &Path) -> io::Result<()> {
    let text = path.to_str().ok_or_else(|| {
        io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("path must be valid UTF-8: {}", path.display()),
        )
    })?;

    if text.is_empty() {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "systemd paths must not be empty",
        ));
    }
    if !path.is_absolute() {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("systemd paths must be absolute: {}", path.display()),
        ));
    }
    if text.chars().any(char::is_whitespace) {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            format!(
                "systemd paths must not contain whitespace: {}",
                path.display()
            ),
        ));
    }

    Ok(())
}

/// Runs `systemctl` with `args` and turns a non-zero exit into an error.
///
/// # Errors
///
/// Returns an error when `systemctl` cannot be spawned or exits unsuccessfully.
/// The failed command's stderr is included in the error message.
pub fn systemctl(args: &[&str]) -> io::Result<()> {
    let output = Command::new("systemctl").args(args).output()?;
    if output.status.success() {
        Ok(())
    } else {
        Err(io::Error::other(format!(
            "systemctl {} failed: {}",
            args.join(" "),
            String::from_utf8_lossy(&output.stderr).trim()
        )))
    }
}

/// Reloads systemd, enables `unit_name`, and optionally restarts it.
///
/// # Errors
///
/// Returns an error when any `systemctl` invocation fails.
pub fn enable_service(unit_name: &str, start: bool) -> io::Result<()> {
    systemctl(&["daemon-reload"])?;
    systemctl(&["enable", unit_name])?;
    if start {
        systemctl(&["restart", unit_name])?;
    }
    Ok(())
}

/// Adds an `Include` line to `~/.ssh/config` that loads rtunnel SSH snippets.
///
/// Returns the snippets directory that OpenSSH will load.
///
/// # Errors
///
/// Returns an error when the SSH directories or configuration file cannot be
/// created, read, or written.
pub fn configure_ssh_include(home: &Path) -> io::Result<PathBuf> {
    let ssh_dir = home.join(".ssh");
    let snippets_dir = ssh_dir.join("rtunnel.d");
    create_private_dir(&ssh_dir)?;
    create_private_dir(&snippets_dir)?;

    let config = ssh_dir.join("config");
    if !config.exists() {
        fs::write(&config, "")?;
    }
    set_mode(&config, 0o600)?;

    let include_line = ssh_include_line(home);
    let contents = fs::read_to_string(&config)?;
    if !contents
        .lines()
        .any(|line| line.trim() == include_line.as_str())
    {
        let mut updated = String::with_capacity(contents.len() + include_line.len() + 3);
        updated.push_str(&include_line);
        updated.push_str("\n\n");
        updated.push_str(&contents);
        fs::write(&config, updated)?;
        set_mode(&config, 0o600)?;
    }

    Ok(snippets_dir)
}

/// Returns the `Include` line that loads rtunnel SSH snippets for `home`.
///
/// Windows OpenSSH does not reliably expand `~`, so the line uses an absolute
/// path with forward slashes and quotes, which also covers home directories
/// containing spaces. Other platforms keep the portable `~` form.
#[must_use]
pub fn ssh_include_line(home: &Path) -> String {
    if cfg!(windows) {
        let pattern = home.join(".ssh").join("rtunnel.d").join("*");
        format!(
            "Include \"{}\"",
            pattern.to_string_lossy().replace('\\', "/")
        )
    } else {
        SSH_INCLUDE_LINE.to_string()
    }
}

fn absolute_path(path: &Path) -> io::Result<PathBuf> {
    if path.is_absolute() {
        Ok(path.to_path_buf())
    } else {
        Ok(std::env::current_dir()?.join(path))
    }
}

fn same_file(left: &Path, right: &Path) -> bool {
    match (fs::canonicalize(left), fs::canonicalize(right)) {
        (Ok(left), Ok(right)) => left == right,
        _ => false,
    }
}

fn temporary_path(dest: &Path) -> io::Result<PathBuf> {
    let file_name = dest.file_name().ok_or_else(|| {
        io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("destination has no file name: {}", dest.display()),
        )
    })?;

    let mut temporary_name = std::ffi::OsString::from(".");
    temporary_name.push(file_name);
    temporary_name.push(format!(".{}.tmp", std::process::id()));

    Ok(dest.with_file_name(temporary_name))
}

fn replace_file(temporary: &Path, dest: &Path) -> io::Result<()> {
    match fs::rename(temporary, dest) {
        Ok(()) => Ok(()),
        Err(error) => {
            // Windows refuses to rename over an existing file. Removing first
            // is also the best effort on Unix for filesystems that reject
            // atomic replacement.
            if dest.exists() {
                fs::remove_file(dest)?;
                fs::rename(temporary, dest)
            } else {
                Err(error)
            }
        }
    }
}

fn systemd_state_name(state_dir: &Path) -> Option<&str> {
    let relative = state_dir.strip_prefix(SYSTEMD_STATE_ROOT).ok()?;
    let mut components = relative.components();
    let name = components.next()?;
    if components.next().is_some() {
        return None;
    }
    name.as_os_str().to_str()
}

#[cfg(unix)]
fn set_mode(path: &Path, mode: u32) -> io::Result<()> {
    use std::os::unix::fs::PermissionsExt;

    let mut permissions = fs::metadata(path)?.permissions();
    permissions.set_mode(mode);
    fs::set_permissions(path, permissions)
}

#[cfg(not(unix))]
#[expect(
    clippy::unnecessary_wraps,
    reason = "keeps the signature identical to the Unix implementation used in `?` chains"
)]
fn set_mode(_path: &Path, _mode: u32) -> io::Result<()> {
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::{
        configure_ssh_include, executable_name, install_self, path_contains, render_unit,
        ssh_include_line,
    };
    use std::ffi::OsStr;
    use std::fs;
    use std::path::Path;

    const TEMPLATE: &str =
        "[Service]\nExecStart=/old/command\nStateDirectory=rtunnel\nProtectSystem=strict\n";

    #[test]
    fn keeps_managed_state_directory() {
        let rendered = render_unit(
            TEMPLATE,
            "/usr/local/bin/rtunneld serve",
            Path::new("/var/lib/rtunnel"),
        );

        assert!(rendered.contains("ExecStart=/usr/local/bin/rtunneld serve\n"));
        assert!(rendered.contains("StateDirectory=rtunnel\n"));
        assert!(!rendered.contains("ReadWritePaths="));
    }

    #[test]
    fn renames_managed_state_directory() {
        let rendered = render_unit(
            TEMPLATE,
            "/bin/rtunneld serve",
            Path::new("/var/lib/custom"),
        );

        assert!(rendered.contains("StateDirectory=custom\n"));
        assert!(!rendered.contains("ReadWritePaths="));
    }

    #[test]
    fn adds_read_write_path_for_custom_state_directory() {
        let rendered = render_unit(TEMPLATE, "/bin/rtunneld serve", Path::new("/opt/rtunnel"));

        assert!(!rendered.contains("StateDirectory="));
        assert!(rendered.contains("ReadWritePaths=/opt/rtunnel\n"));
    }

    #[test]
    fn adds_ssh_include_once() {
        let home = tempfile::tempdir().expect("temporary home directory");
        let first = configure_ssh_include(home.path()).expect("configure ssh include");
        let second = configure_ssh_include(home.path()).expect("configure ssh include twice");

        assert_eq!(first, second);
        let config = fs::read_to_string(home.path().join(".ssh/config")).expect("read ssh config");
        assert_eq!(
            config
                .matches(ssh_include_line(home.path()).as_str())
                .count(),
            1
        );
    }

    #[test]
    fn keeps_unix_include_line_portable() {
        #[cfg(unix)]
        assert_eq!(
            ssh_include_line(Path::new("/home/alice")),
            "Include ~/.ssh/rtunnel.d/*"
        );
    }

    #[test]
    fn uses_absolute_windows_include_line() {
        #[cfg(windows)]
        assert_eq!(
            ssh_include_line(Path::new(r"C:\Users\Alice Smith")),
            "Include \"C:/Users/Alice Smith/.ssh/rtunnel.d/*\""
        );
    }

    #[test]
    fn appends_platform_executable_suffix() {
        assert_eq!(
            executable_name("rtunnel"),
            format!("rtunnel{}", super::EXE_SUFFIX)
        );
    }

    #[test]
    fn detects_path_entries() {
        #[cfg(unix)]
        {
            let path = OsStr::new("/usr/bin:/opt/rtunnel/:\"/opt/with space\"");
            assert!(path_contains(path, Path::new("/opt/rtunnel")));
            assert!(path_contains(path, Path::new("/opt/with space")));
            assert!(!path_contains(path, Path::new("/opt/rtunnel/bin")));
            assert!(path_contains(OsStr::new("/"), Path::new("/")));
        }

        #[cfg(windows)]
        {
            let path = OsStr::new(r"C:\Windows;C:\Program Files\RTunnel\;");
            assert!(path_contains(path, Path::new(r"c:\program files\rtunnel")));
            assert!(!path_contains(path, Path::new(r"C:\Windows\System32")));
        }
    }

    #[test]
    fn installs_self_as_executable() {
        let dir = tempfile::tempdir().expect("temporary install directory");
        let dest = dir.path().join("bin").join("rtunnel");
        let installed = install_self(&dest).expect("install self");

        assert_eq!(installed, dest);
        assert!(installed.is_file());

        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;

            let mode = fs::metadata(&installed)
                .expect("installed metadata")
                .permissions()
                .mode()
                & 0o777;
            assert_eq!(mode, 0o755);
        }
    }
}
